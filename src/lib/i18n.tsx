interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  tFilesCount: (count: number) => string;
  tSnippetsCount: (count: number) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function getNestedValue(obj: any, path: string): string | undefined {
  const parts = path.split(".");
  let current = obj;
  for (const part of parts) {
    if (current && typeof current === "object" && part in current) {
      current = current[part];
    } else {
      return undefined;
    }
  }
  return typeof current === "string" ? current : undefined;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("ru");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("snippetvault_lang") as Locale;
      if (saved === "ru" || saved === "en") {
        setLocaleState(saved);
        if (typeof document !== "undefined") {
          document.documentElement.lang = saved;
        }
      }
    } catch {}
  }, []);

  const setLocale = (newLocale: Locale) => {
    setLocaleState(newLocale);
    try {
      localStorage.setItem("snippetvault_lang", newLocale);
      if (typeof document !== "undefined") {
        document.documentElement.lang = newLocale;
      }
    } catch {}
  };

  const t = useMemo(() => {
    return (key: string, vars?: Record<string, string | number>): string => {
      let str = getNestedValue(translations[locale], key);
      if (!str) {
        // Fallback to Russian
        str = getNestedValue(translations.ru, key);
      }
      if (!str) {
        return key;
      }
      if (vars) {
        Object.entries(vars).forEach(([k, v]) => {
          str = str!.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
        });
      }
      return str;
    };
  }, [locale]);

  const tFilesCount = useMemo(() => {
    return (count: number): string => {
      if (locale === "ru") {
        const mod10 = count % 10;
        const mod100 = count % 100;
        if (mod100 >= 11 && mod100 <= 19) return `${count} файлов`;
        if (mod10 === 1) return `${count} файл`;
        if (mod10 >= 2 && mod10 <= 4) return `${count} файла`;
        return `${count} файлов`;
      }
      return count === 1 ? "1 file" : `${count} files`;
    };
  }, [locale]);

  const tSnippetsCount = useMemo(() => {
    return (count: number): string => {
      if (locale === "ru") {
        const mod10 = count % 10;
        const mod100 = count % 100;
        if (mod100 >= 11 && mod100 <= 19) return `${count} сниппетов`;
        if (mod10 === 1) return `${count} сниппет`;
        if (mod10 >= 2 && mod10 <= 4) return `${count} сниппета`;
        return `${count} сниппетов`;
      }
      return count === 1 ? "1 snippet" : `${count} snippets`;
    };
  }, [locale]);

  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t,
      tFilesCount,
      tSnippetsCount,
    }),
    [locale, t, tFilesCount, tSnippetsCount]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    // Graceful fallback if called outside provider
    const t = (key: string, vars?: Record<string, string | number>) => {
      let str = getNestedValue(translations.ru, key) || key;
      if (vars) {
        Object.entries(vars).forEach(([k, v]) => {
          str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
        });
      }
      return str;
    };
    return {
      locale: "ru",
      setLocale: () => {},
      t,
      tFilesCount: (count: number) => `${count} файл`,
      tSnippetsCount: (count: number) => `${count} сниппет`,
    };
  }
  return ctx;
}

